-- AGGIORNAMENTO SALDO (eseguito post-inserimento transazioni)
UPDATE Utente u
SET Saldo = COALESCE((
    SELECT SUM(Importo) 
    FROM Transazione 
    WHERE ID_Utente = u.ID_Utente
    AND Tipo != 'INCASSO_SOSPESO'
), 0.00);
