-- INCASSI AUTOMATICI PER OGNI PRENOTAZIONE
INSERT INTO Transazione (ID_Utente, ID_Prenotazione, Tipo, Importo, Descrizione)
SELECT 
    g.ID_Gestore,
    p.ID_Prenotazione,
    CASE 
        WHEN p.Stato = 'ATTIVA' THEN 'INCASSO_SOSPESO'
        WHEN p.Stato = 'CONCLUSA' THEN 'INCASSO_COMPLETATO'
    END,
    p.PrezzoTotale,
    CASE 
        WHEN p.Stato = 'ATTIVA' THEN CONCAT('Incasso in sospeso per prenotazione ', p.CodicePrenotazione)
        WHEN p.Stato = 'CONCLUSA' THEN CONCAT('Incasso per prenotazione ', p.CodicePrenotazione)
    END
FROM Prenotazione p
JOIN PostoAuto pa ON p.ID_Posto = pa.ID_Posto
JOIN Garage g ON pa.ID_Garage = g.ID_Garage
WHERE p.Stato IN ('ATTIVA', 'CONCLUSA');

